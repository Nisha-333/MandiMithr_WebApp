export function getStateById(stateId: string): StateData | undefined {
  return indiaGeography.find(s => s.id === stateId);
}

export function getDistrictById(stateId: string, districtId: string): District | undefined {
  const state = getStateById(stateId);
  return state?.districts.find(d => d.id === districtId);
}

export function getAllStates(): StateData[] {
  return indiaGeography.sort((a, b) => a.name.localeCompare(b.name));
}

export function getDistrictsByState(stateId: string): District[] {
  const state = getStateById(stateId);
  return state?.districts.sort((a, b) => a.name.localeCompare(b.name)) || [];
}
